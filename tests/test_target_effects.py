import unittest
from pathlib import Path

from tests.lua_test_runner import run_lua_test

ROOT = Path(__file__).resolve().parents[1]


def read(*parts):
    return ROOT.joinpath(*parts).read_text(encoding="utf-8-sig")


# Describe: what a spell did to the target shows in the game's own word.
class TargetEffectTests(unittest.TestCase):
    def test_effects_show_when_an_aura_lands_with_the_cast_or_its_hit(self):
        # Given
        script = "target_effects.lua"

        # When
        result = run_lua_test(script)

        # Then
        self.assertEqual(result.returncode, 0, result.stderr or result.stdout)

    def test_the_notice_is_loaded_fed_and_configurable(self):
        # Given
        reader = read("Combat", "Reader.lua")
        engine = read("Components", "CombatEngine.lua")

        # When / Then
        for toc in ("MikScrollingBattleText.toc", "MikScrollingBattleText_Camelot.toc"):
            lines = read(toc).splitlines()
            spells = lines.index("Combat\\Spells.lua")
            self.assertEqual(
                lines[spells + 1:spells + 3],
                ["Combat\\SpellMechanics.lua", "Combat\\Effects.lua"],
            )
        self.assertIn("ns.NoteEffectCast(unit, spell, now, key)", reader)
        self.assertIn("ns.NoteEffectHit(record, at)", reader)
        self.assertIn("router.Effect = ", engine)
        self.assertEqual(read("MSBTProfiles.lua").count("\tOUTGOING_EFFECT = {"), 2)
        self.assertIn(
            'EventsTab_AddEvent(category, "OUTGOING_EFFECT"',
            read("MSBTOptions", "MSBTOptionsTabs.lua"),
        )
        self.assertIn(
            'obj["OUTGOING_EFFECT"]',
            read("MSBTOptions", "Localization", "localization.lua"),
        )

    def test_the_spell_table_matches_its_generator(self):
        # Given
        from scripts import generate_spell_mechanics as generator

        table = read("Combat", "SpellMechanics.lua")
        categories = [
            {"SpellID": "710", "Mechanic": "18", "DifficultyID": "0"},
            {"SpellID": "205", "Mechanic": "0", "DifficultyID": "0"},
            {"SpellID": "8", "Mechanic": "21", "DifficultyID": "0"},
        ]
        effects = [
            {"SpellID": "205", "EffectIndex": "1", "EffectMechanic": "0", "DifficultyID": "0"},
            {"SpellID": "205", "EffectIndex": "0", "EffectMechanic": "11", "DifficultyID": "0"},
            {"SpellID": "710", "EffectIndex": "0", "EffectMechanic": "12", "DifficultyID": "0"},
            {"SpellID": "9", "EffectIndex": "0", "EffectMechanic": "15", "DifficultyID": "1"},
        ]

        # When
        found = generator.mechanics(categories, effects)
        rendered = generator.render(found, "test")

        # Then
        self.assertEqual(found, {205: 11, 710: 18})
        self.assertIn("    [205]=11, [710]=18,\n", rendered)
        self.assertIn("[205]=11,", table)
        self.assertIn("[1822]=15,", table)
        self.assertTrue(table.startswith("-- Generated by scripts/generate_spell_mechanics.py"))


if __name__ == "__main__":
    unittest.main()
