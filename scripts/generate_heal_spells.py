"""Generate Combat/HealSpells.lua from the client's own spell tables.

The client gives addons no way to ask, in every language, whether a spell
heals at once or over time, how often it ticks and how long it lasts; the
spell description is localized text. So these facts are taken from the game
data and shipped as a table of spell id to heal facts, for every spell whose
own effects heal. The addon reads the table on Forever only.

Usage:
    python scripts/generate_heal_spells.py SpellEffect.csv SpellMisc.csv SpellDuration.csv Spell.csv BUILD

The four files are CSV exports of the tables of the same name for the client
build named BUILD (for example 1.60.1.70888); Spell.csv is the English one. A
spell heals at once when one of its effects heals (Effect 10, 67, 75 or 136)
and over time when one of its effects applies a periodic heal aura (EffectAura
8, or 20 for a percentage) with a period. It heals your pet when such an
effect targets the pet (ImplicitTarget 5). Its duration comes from
SpellMisc.DurationIndex.

A spell can heal through something these effects do not show: a dummy or
script effect, a spell it triggers or a unit it summons. Such a spell whose
English description speaks of healing is listed as unknown, so the addon reads
its description as for a spell newer than the table. The highest spell id of
the build is written too: the table takes a spell up to it that is in neither
list not to heal, which misses a heal through an effect it does not read.
"""
import csv
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUTPUT = ROOT / "Combat" / "HealSpells.lua"
# Heal, heal for maximum health, heal mechanical, heal for a percentage.
HEAL_EFFECTS = {10, 67, 75, 136}
# Periodic heal, periodic heal for a percentage.
PERIODIC_HEAL_AURAS, PET_TARGET = {8, 20}, 5
# Dummy, summon, trigger spell, script effect, force cast, trigger spell with value.
HIDDEN_EFFECTS = {3, 28, 64, 77, 140, 142}
# Dummy, periodic trigger spell, proc trigger spell, periodic dummy, periodic trigger with value.
HIDDEN_AURAS = {4, 23, 42, 226, 227}
PER_LINE = 6


def read(path):
    with open(path, encoding="utf-8", newline="") as handle:
        return list(csv.DictReader(handle))


def seconds(milliseconds):
    return "%g" % (milliseconds / 1000.0)


def heal_facts(effects, misc, durations, spells):
    direct, period, pet, hidden = set(), {}, set(), set()
    for row in effects:
        if int(row["DifficultyID"]) != 0:
            continue
        spell = int(row["SpellID"])
        heals = int(row["Effect"]) in HEAL_EFFECTS
        if heals:
            direct.add(spell)
        if int(row["EffectAura"]) in PERIODIC_HEAL_AURAS and int(row["EffectAuraPeriod"]) > 0:
            period.setdefault(spell, int(row["EffectAuraPeriod"]))
            heals = True
        if heals and int(row["ImplicitTarget_0"]) == PET_TARGET:
            pet.add(spell)
        if int(row["Effect"]) in HIDDEN_EFFECTS or int(row["EffectAura"]) in HIDDEN_AURAS:
            hidden.add(spell)
    lengths = {int(row["ID"]): int(row["Duration"]) for row in durations}
    duration = {}
    for row in misc:
        if int(row["DifficultyID"]) == 0:
            duration[int(row["SpellID"])] = max(lengths.get(int(row["DurationIndex"]), 0), 0)
    found = {}
    for spell in direct | set(period):
        found[spell] = (1 if spell in direct else 0, period.get(spell, 0), duration.get(spell, 0),
                        1 if spell in pet else 0)
    speaks = {int(row["ID"]) for row in spells if "heal" in (row["Description_lang"] or "").lower()}
    unknown = (hidden & speaks) - set(found)
    last = max(int(row["SpellID"]) for row in effects + misc)
    return found, unknown, last


def render(found, unknown, last, build):
    lines = [
        "-- Generated by scripts/generate_heal_spells.py from the client's spell",
        "-- tables, build %s, for Forever. Do not edit by hand." % build,
        "-- Spell id to { heals at once (1 or 0), seconds between ticks of its heal",
        "-- over time (0 for none), duration in seconds (0 for none or unlimited),",
        "-- heals your pet (1 or 0) }, for each spell whose own effects heal",
        "-- (Healing.lua). HEAL_SPELLS_UNKNOWN lists spells that may heal through a",
        "-- dummy effect, a triggered spell or a summoned unit; their description",
        "-- decides. A spell id up to HEAL_SPELLS_LAST in neither list is taken not",
        "-- to heal.",
        "MikSBT.CombatEngine.HEAL_SPELLS_LAST = %d" % last,
        "MikSBT.CombatEngine.HEAL_SPELLS = {",
    ]
    entries = ["[%d]={%d,%s,%s,%d}," % (spell, facts[0], seconds(facts[1]), seconds(facts[2]), facts[3])
               for spell, facts in sorted(found.items())]
    for start in range(0, len(entries), PER_LINE):
        lines.append("    " + " ".join(entries[start:start + PER_LINE]))
    lines.append("}")
    lines.append("MikSBT.CombatEngine.HEAL_SPELLS_UNKNOWN = {")
    entries = ["[%d]=true," % spell for spell in sorted(unknown)]
    for start in range(0, len(entries), PER_LINE * 2):
        lines.append("    " + " ".join(entries[start:start + PER_LINE * 2]))
    lines.append("}")
    return "\n".join(lines) + "\n"


def main():
    effects, misc, durations, spells, build = sys.argv[1:6]
    found, unknown, last = heal_facts(read(effects), read(misc), read(durations), read(spells))
    OUTPUT.write_text(render(found, unknown, last, build), encoding="utf-8", newline="\n")
    print("%d spells and %d unknown written to %s" % (len(found), len(unknown), OUTPUT.relative_to(ROOT)))


if __name__ == "__main__":
    main()
