"""Generate Combat/SpellMechanics.lua from the client's own spell tables.

The client gives addons no way to ask what a spell does to its target, so the
mechanic of each spell (snare, bleed, banish, ...) is taken from the game
data and shipped as a table of spell id to mechanic id.

Usage:
    python scripts/generate_spell_mechanics.py --build BUILD --csv-dir FOLDER

FOLDER holds SpellCategories.csv and SpellEffect.csv, CSV exports of the tables
of the same name for the client build named BUILD (for example 1.60.1.70888). A spell's own mechanic
(SpellCategories.Mechanic) wins over the mechanic of its first effect that
has one (SpellEffect.EffectMechanic). Only the mechanics the engine has a
word for are kept (Combat/Effects.lua, WORDS).
"""
import argparse
import csv
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUTPUT = ROOT / "Combat" / "SpellMechanics.lua"
# Mechanic ids as SpellMechanic lists them; keep in step with WORDS.
SHOWN = {1, 2, 3, 5, 7, 8, 9, 10, 11, 12, 13, 14, 15, 17, 18, 20, 22, 23, 24, 27, 30}
PER_LINE = 8
TABLE = "SpellMechanics"
SCRIPT = "scripts/generate_spell_mechanics.py"
# The client's name in the data the CSV files come from.
PRODUCT = "wowf"
BUILD_PATTERN = re.compile(r"^\d+\.\d+\.\d+\.\d+$")


def build_argument(text):
    if not BUILD_PATTERN.match(text):
        raise argparse.ArgumentTypeError("a build looks like 1.60.1.70888, not %r" % text)
    return text


# The two lines by which the table names its source: the product and build of the data, and this script.
def registration(build):
    return [
        "MikSBT.TABLE_BUILDS = MikSBT.TABLE_BUILDS or {}",
        'MikSBT.TABLE_BUILDS.%s = { product = "%s", build = "%s", script = "%s" }'
        % (TABLE, PRODUCT, build, SCRIPT),
    ]


def read(path):
    with open(path, encoding="utf-8", newline="") as handle:
        return list(csv.DictReader(handle))


def mechanics(categories, effects):
    found = {}
    for row in sorted(effects, key=lambda row: (int(row["SpellID"]), int(row["EffectIndex"]))):
        mechanic = int(row["EffectMechanic"])
        if int(row["DifficultyID"]) == 0 and mechanic in SHOWN:
            found.setdefault(int(row["SpellID"]), mechanic)
    for row in categories:
        mechanic = int(row["Mechanic"])
        if int(row["DifficultyID"]) == 0 and mechanic in SHOWN:
            found[int(row["SpellID"])] = mechanic
    return found


def render(found, build):
    lines = [
        "-- Generated by scripts/generate_spell_mechanics.py from the client's spell",
        "-- tables, build %s. Do not edit by hand." % build,
        "-- Spell id to mechanic id: what a spell does to its target (Effects.lua).",
    ]
    lines += registration(build)
    lines.append("MikSBT.CombatEngine.SPELL_MECHANICS = {")
    entries = ["[%d]=%d," % item for item in sorted(found.items())]
    for start in range(0, len(entries), PER_LINE):
        lines.append("    " + " ".join(entries[start:start + PER_LINE]))
    lines.append("}")
    return "\n".join(lines) + "\n"


def generate(csv_dir, build):
    return render(mechanics(read(csv_dir / "SpellCategories.csv"), read(csv_dir / "SpellEffect.csv")), build)


def main():
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--build", required=True, type=build_argument,
                        help="client build of the CSV files, for example 1.60.1.70888")
    parser.add_argument("--csv-dir", required=True, type=Path,
                        help="folder with SpellCategories.csv and SpellEffect.csv")
    args = parser.parse_args()
    OUTPUT.write_text(generate(args.csv_dir, args.build), encoding="utf-8", newline="\n")
    print("%s written from build %s" % (OUTPUT.relative_to(ROOT), args.build))


if __name__ == "__main__":
    main()
