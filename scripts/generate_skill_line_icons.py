"""Generate Components/SkillLineIcons.lua from the client's skill line table.

A skill gain names its skill line, and a spell of the same name does not give
the line's icon: the client has a spell named after every profession, all with
the same gem icon. So each skill line's own icon is taken from the game data
and shipped as a table of skill line id to icon file id.

Usage:
    python scripts/generate_skill_line_icons.py SkillLine.csv BUILD

The file is a CSV export of the SkillLine table for the client build named
BUILD (for example 1.60.1.70888). Lines whose icon is a placeholder are left
out, so their gains keep the icon they had.
"""
import csv
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUTPUT = ROOT / "Components" / "SkillLineIcons.lua"
# No icon, the "Temp" icon of weapon, armour and language lines, the question mark.
PLACEHOLDERS = {0, 136235, 134400}
PER_LINE = 6


def icons(rows):
    found = {}
    for row in rows:
        icon = int(row["SpellIconFileID"])
        if icon not in PLACEHOLDERS:
            found[int(row["ID"])] = icon
    return found


def render(found, build):
    lines = [
        "-- Generated by scripts/generate_skill_line_icons.py from the client's skill",
        "-- line table, build %s. Do not edit by hand." % build,
        "-- Skill line id to icon file id (ParserNotifications.lua, SkillIcon).",
        "MikSBT.SKILL_LINE_ICONS = {",
    ]
    entries = ["[%d]=%d," % item for item in sorted(found.items())]
    for start in range(0, len(entries), PER_LINE):
        lines.append("\t" + " ".join(entries[start:start + PER_LINE]))
    lines.append("}")
    return "\n".join(lines) + "\n"


def main():
    path, build = sys.argv[1:3]
    with open(path, encoding="utf-8", newline="") as handle:
        found = icons(csv.DictReader(handle))
    OUTPUT.write_text(render(found, build), encoding="utf-8", newline="\n")
    print("%d skill lines written to %s" % (len(found), OUTPUT.relative_to(ROOT)))


if __name__ == "__main__":
    main()
