"""Generate Combat/DamageShields.lua from the client's spell tables.

A damage shield (Thorns, Retribution Aura, an item's) hurts whoever strikes
you. Its combat log line says that a damage shield struck, never which one,
and nothing tells a damage shield from any other buff. So the spells whose
aura is a damage shield are taken from the game data, with their school, and
shipped as a table of spell id to school mask.

Usage:
    python scripts/generate_damage_shields.py --build BUILD --csv-dir FOLDER

FOLDER holds SpellEffect.csv and SpellMisc.csv, CSV exports of the tables of the
same name for the client build named BUILD (for example 1.60.1.70888).
"""
import argparse
import csv
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUTPUT = ROOT / "Combat" / "DamageShields.lua"
# The aura that hurts whoever strikes its bearer.
DAMAGE_SHIELD_AURA = 15
PER_LINE = 6
TABLE = "DamageShields"
SCRIPT = "scripts/generate_damage_shields.py"
# The client's name in the data the CSV files come from.
PRODUCT = "wowf"
BUILD_PATTERN = re.compile(r"^\d+\.\d+\.\d+\.\d+$")


def build_argument(text):
    if not BUILD_PATTERN.match(text):
        raise argparse.ArgumentTypeError("a build looks like 1.60.1.70888, not %r" % text)
    return text


# The two lines by which the table names its source: the product and build of the data, and this script.
def registration(build):
    return [
        "MikSBT.TABLE_BUILDS = MikSBT.TABLE_BUILDS or {}",
        'MikSBT.TABLE_BUILDS.%s = { product = "%s", build = "%s", script = "%s" }'
        % (TABLE, PRODUCT, build, SCRIPT),
    ]


def read(path):
    with open(path, encoding="utf-8", newline="") as handle:
        return list(csv.DictReader(handle))


def shields(effects, misc):
    spells = {int(row["SpellID"]) for row in effects
              if int(row["EffectAura"]) == DAMAGE_SHIELD_AURA and int(row["DifficultyID"]) == 0}
    found = {}
    for row in misc:
        spell = int(row["SpellID"])
        if spell in spells and int(row["DifficultyID"]) == 0:
            found[spell] = int(row["SchoolMask"])
    return found


def render(found, build):
    lines = [
        "-- Generated by scripts/generate_damage_shields.py from the client's spell",
        "-- tables, build %s. Do not edit by hand." % build,
        "-- Spell id of a damage shield to its school mask (Reader.lua, ShieldSpell).",
    ]
    lines += registration(build)
    lines.append("MikSBT.DAMAGE_SHIELDS = {")
    entries = ["[%d]=%d," % item for item in sorted(found.items())]
    for start in range(0, len(entries), PER_LINE):
        lines.append("\t" + " ".join(entries[start:start + PER_LINE]))
    lines.append("}")
    return "\n".join(lines) + "\n"


def generate(csv_dir, build):
    return render(shields(read(csv_dir / "SpellEffect.csv"), read(csv_dir / "SpellMisc.csv")), build)


def main():
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--build", required=True, type=build_argument,
                        help="client build of the CSV files, for example 1.60.1.70888")
    parser.add_argument("--csv-dir", required=True, type=Path,
                        help="folder with SpellEffect.csv and SpellMisc.csv")
    args = parser.parse_args()
    OUTPUT.write_text(generate(args.csv_dir, args.build), encoding="utf-8", newline="\n")
    print("%s written from build %s" % (OUTPUT.relative_to(ROOT), args.build))


if __name__ == "__main__":
    main()
