"""Generate Combat/DamageShields.lua from the client's spell tables.

A damage shield (Thorns, Retribution Aura, an item's) hurts whoever strikes
you. Its combat log line says that a damage shield struck, never which one,
and nothing tells a damage shield from any other buff. So the spells whose
aura is a damage shield are taken from the game data, with their school, and
shipped as a table of spell id to school mask.

Usage:
    python scripts/generate_damage_shields.py SpellEffect.csv SpellMisc.csv BUILD

The files are CSV exports of the SpellEffect and SpellMisc tables for the
client build named BUILD (for example 1.60.1.70888).
"""
import csv
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUTPUT = ROOT / "Combat" / "DamageShields.lua"
# The aura that hurts whoever strikes its bearer.
DAMAGE_SHIELD_AURA = 15
PER_LINE = 6


def shields(effects, misc):
    spells = {int(row["SpellID"]) for row in effects
              if int(row["EffectAura"]) == DAMAGE_SHIELD_AURA and int(row["DifficultyID"]) == 0}
    found = {}
    for row in misc:
        spell = int(row["SpellID"])
        if spell in spells and int(row["DifficultyID"]) == 0:
            found[spell] = int(row["SchoolMask"])
    return found


def render(found, build):
    lines = [
        "-- Generated by scripts/generate_damage_shields.py from the client's spell",
        "-- tables, build %s. Do not edit by hand." % build,
        "-- Spell id of a damage shield to its school mask (Reader.lua, ShieldSpell).",
        "MikSBT.DAMAGE_SHIELDS = {",
    ]
    entries = ["[%d]=%d," % item for item in sorted(found.items())]
    for start in range(0, len(entries), PER_LINE):
        lines.append("\t" + " ".join(entries[start:start + PER_LINE]))
    lines.append("}")
    return "\n".join(lines) + "\n"


def main():
    effects_path, misc_path, build = sys.argv[1:4]
    with open(effects_path, encoding="utf-8", newline="") as effects, \
            open(misc_path, encoding="utf-8", newline="") as misc:
        found = shields(csv.DictReader(effects), csv.DictReader(misc))
    OUTPUT.write_text(render(found, build), encoding="utf-8", newline="\n")
    print("%d damage shields written to %s" % (len(found), OUTPUT.relative_to(ROOT)))


if __name__ == "__main__":
    main()
