"""Generate Components/SkillLineIcons.lua from the client's skill line table.

A skill gain names its skill line, and a spell of the same name does not give
the line's icon: the client has a spell named after every profession, all with
the same gem icon. So each skill line's own icon is taken from the game data
and shipped as a table of skill line id to icon file id.

Usage:
    python Developer/generate_skill_line_icons.py --build BUILD --csv-dir FOLDER

FOLDER holds SkillLine.csv, a CSV export of the SkillLine table for the client
build named BUILD (for example 1.60.1.70888). Lines whose icon is a placeholder are left
out, so their gains keep the icon they had.
"""
import argparse
import csv
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUTPUT = ROOT / "Components" / "SkillLineIcons.lua"
BUILD_METADATA = Path(__file__).with_name("SkillLineIconsBuild.lua")
# No icon, the "Temp" icon of weapon, armour and language lines, the question mark.
PLACEHOLDERS = {0, 136235, 134400}
PER_LINE = 6
TABLE = "SkillLineIcons"
SCRIPT = "Developer/generate_skill_line_icons.py"
# The client's name in the data the CSV files come from.
PRODUCT = "wowf"
BUILD_PATTERN = re.compile(r"^\d+\.\d+\.\d+\.\d+$")


def build_argument(text):
    if not BUILD_PATTERN.match(text):
        raise argparse.ArgumentTypeError("a build looks like 1.60.1.70888, not %r" % text)
    return text


def render_build_metadata(build):
    lines = [
        "-- Generated by %s. Do not edit by hand." % SCRIPT,
        "MikSBT.TABLE_BUILDS = MikSBT.TABLE_BUILDS or {}",
        'MikSBT.TABLE_BUILDS.%s = { product = "%s", build = "%s", script = "%s" }'
        % (TABLE, PRODUCT, build, SCRIPT),
    ]
    return "\n".join(lines) + "\n"


def read(path):
    with open(path, encoding="utf-8", newline="") as handle:
        return list(csv.DictReader(handle))


def icons(rows):
    found = {}
    for row in rows:
        icon = int(row["SpellIconFileID"])
        if icon not in PLACEHOLDERS:
            found[int(row["ID"])] = icon
    return found


def render(found, build):
    lines = [
        "-- Generated by %s from the client's" % SCRIPT,
        "-- skill line table, build %s. Do not edit by hand." % build,
        "-- Skill line id to icon file id (ParserNotifications.lua, SkillIcon).",
    ]
    lines.append("MikSBT.SKILL_LINE_ICONS = {")
    entries = ["[%d]=%d," % item for item in sorted(found.items())]
    for start in range(0, len(entries), PER_LINE):
        lines.append("\t" + " ".join(entries[start:start + PER_LINE]))
    lines.append("}")
    return "\n".join(lines) + "\n"


def generate(csv_dir, build):
    return render(icons(read(csv_dir / "SkillLine.csv")), build)


def main():
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--build", required=True, type=build_argument,
                        help="client build of the CSV files, for example 1.60.1.70888")
    parser.add_argument("--csv-dir", required=True, type=Path,
                        help="folder with SkillLine.csv")
    args = parser.parse_args()
    OUTPUT.write_text(generate(args.csv_dir, args.build), encoding="utf-8", newline="\n")
    BUILD_METADATA.write_text(
        render_build_metadata(args.build), encoding="utf-8", newline="\n"
    )
    for path in (OUTPUT, BUILD_METADATA):
        print("%s written from build %s" % (path.relative_to(ROOT), args.build))


if __name__ == "__main__":
    main()
